export const BUILTIN_WALLPAPERS = {
  champagne: { svg: champagne, base: "#928980", glass: "84 74 64" },
  teal: { svg: teal(), base: "#174c46", glass: "255 255 255" },
} as const;

export type BuiltinWallpaper = keyof typeof BUILTIN_WALLPAPERS;

export const isBuiltin = (v: unknown): v is BuiltinWallpaper => v === "champagne" || v === "teal";

/** CSS background value for a built-in wallpaper or an image URL. */
export function wallpaperCss(value: string): string {
  if (isBuiltin(value)) {
    const w = BUILTIN_WALLPAPERS[value];
    return `${w.base} center / cover no-repeat url("data:image/svg+xml;charset=utf-8,${encodeURIComponent(w.svg)}")`;
  }
  return `center / cover no-repeat url("${value.replace(/"/g, "%22")}")`;
}
